const getMessage = (language, key) => key.split('.').reduce((value, part) => value?.[part], messages[language]);

const interpolate = (value, vars = {}) => {
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? '');
};

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
      if (saved === 'th' || saved === 'en') return saved;
    } catch {
      // Fall back to the browser language when storage is unavailable.
    }
    return navigator.language?.toLowerCase().startsWith('th') ? 'th' : 'en';
  });

  const changeLanguage = (nextLanguage) => {
    const next = nextLanguage === 'th' ? 'th' : 'en';
    setLanguage(next);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch {
      // The UI still switches when storage is unavailable.
    }
  };

  const value = useMemo(() => ({
    language,
    setLanguage: changeLanguage,
    t: (key, vars) => interpolate(getMessage(language, key) ?? getMessage('en', key) ?? key, vars),
    get: (key) => getMessage(language, key) ?? getMessage('en', key) ?? key,
  }), [language]);

  return createElement(LanguageContext.Provider, { value }, children);
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}
